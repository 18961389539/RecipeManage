/** 取术语解释；未收录时返回 undefined，调用方降级为不带提示的普通文本。 */
/**
 * 术语解释的唯一出口，i18n 也只在这里接一次：表里继续存中文（那是键与缺省显示），取用时过一层 t()。
 * 键本身（如「四步握手」）同时也是界面上渲染的词，HelpTip 的 slot 已经在视图里 $t 过了。
 */
export function tipOf(key?: string | null): string | undefined {
  if (!key) return undefined;
  const entry = D[key];
  if (!entry) return undefined;
  return entry.detail ? `${t(entry.text)}\n\n${t(entry.detail)}` : t(entry.text);
}

export function hasTip(key?: string | null): boolean {
  return !!key && key in D;
}
